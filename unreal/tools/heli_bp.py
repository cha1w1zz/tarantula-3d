dsl('PickPoi', '''
(fn PickPoi ()
  (Variables|Default|SetPoiT (Math|Random|RandomFloatinRange 25.0 45.0))
  (bind hs (Actor|GetAllActorsOfClass :ActorClass "/Game/Game/BP_Human.BP_Human_C"))
  (bind n (Utilities|Array|Length hs))
  (if (and (> n 0) (< (Math|Random|RandomFloat) 0.7))
    (Variables|Default|SetPoi (Utilities|Array|Get(acopy) hs (Math|Float|Truncate (* (Math|Random|RandomFloat) (* n 0.999)))))
    (Variables|Default|SetOrbT 14.0)
    (Variables|Default|SetMode 5)
    (return))
  (if (and (Valid :A Spider) (< (Math|Random|RandomFloat) 0.6))
    (if (>= (Class|BPTarantula|GetSpan :self Spider) 1200.0)
      (Variables|Default|SetPoi Spider)
      (Variables|Default|SetOrbT 14.0)
      (Variables|Default|SetMode 5))))
''')

# patrol point on the drifting ellipse, a bit ahead of Ang (the carrot the helicopter chases)
fn('Patrol', [('DT', 'float')])
dsl('Patrol', '''
(fn Patrol (DT)
  (Variables|Default|SetPoiT (- PoiT DT))
  (bind w (+ 0.09 (* 0.03 (Math|Trig|Sin(Radians) (+ (* T 0.05) Phase)))))
  (Variables|Default|SetAng (+ Ang (* (* Dir w) DT)))
  (bind la (+ Ang (* Dir 0.4)))
  (bind rk (+ 1.0 (* 0.16 (Math|Trig|Sin(Radians) (+ (* T 0.07) Phase)))))
  (bind alt (Math|Float|Min(Float) 5000.0 (+ (+ Alt (* 350.0 (Math|Trig|Sin(Radians) (+ (* T 0.11) Phase)))) 0.0)))
  (bind p (Math|Vector|MakeVector (* (* RX rk) (Math|Trig|Cos(Radians) la)) (* (* RY (- 2.0 rk)) (Math|Trig|Sin(Radians) la)) alt))
  (bind a (Fly :P p :Spd 750.0 :DT DT))
  (if (<= PoiT 0.0) (PickPoi)))
''')

# circle Poi at 19 m for OrbT s, then back onto the ellipse where it is now
fn('Orbit', [('DT', 'float')])
dsl('Orbit', '''
(fn Orbit (DT)
  (bind here (Transformation|GetActorLocation))
  (Variables|Default|SetOrbT (- OrbT DT))
  (if (or (<= OrbT 0.0) (not (Valid :A Poi)))
    (Variables|Default|SetMode 0)
    (Variables|Default|SetAng (Math|Trig|DegreesToRadians (Math|Trig|Atan2(Degrees) (/ (.y here) RY) (/ (.x here) RX))))
    (return))
  (Variables|Default|SetOrbA (+ OrbA (* (* Dir 0.3) DT)))
  (bind pp (Transformation|GetActorLocation :self Poi))
  (bind a (Fly :P (Math|Vector|MakeVector (+ (.x pp) (* 1900.0 (Math|Trig|Cos(Radians) OrbA))) (+ (.y pp) (* 1900.0 (Math|Trig|Sin(Radians) OrbA)))
                (Math|Float|Max(Float) 2700.0 (- Alt 700.0))) :Spd 650.0 :DT DT)))
''')

# rescue: 1 over him at cruise height, 2 spiral down 10 s (radius 9 m -> 0, slower near the ground), 3 hover 2.5 s + board, 4 climb out
fn('RescueTick', [('DT', 'float')])
dsl('RescueTick', '''
(fn RescueTick (DT)
  (bind here (Transformation|GetActorLocation))
  (bind tv (Valid :A Target))
  (if (and (and (>= Mode 1) (<= Mode 2)) (not tv))
    (Variables|Default|SetMode 4)
    (Variables|Default|SetT 0.0))
  (if (== Mode 1)
    (bind tp (Transformation|GetActorLocation :self Target))
    (if (Fly :P (Math|Vector|MakeVector (.x tp) (.y tp) Alt) :Spd 1000.0 :DT DT)
      (Variables|Default|SetMode 2)
      (Variables|Default|SetA0 (.z here))
      (Variables|Default|SetT 0.0))
    (return))
  (if (== Mode 2)
    (bind tp2 (Transformation|GetActorLocation :self Target))
    (bind u (Math|Float|Clamp(Float) (/ T 10.0) 0.0 1.0))
    (bind e (- 1.0 (* (- 1.0 u) (- 1.0 u))))
    (bind r (* 900.0 (- 1.0 e)))
    (bind sa (* T 0.8))
    (bind a2 (Fly :P (Math|Vector|MakeVector (+ (.x tp2) (* r (Math|Trig|Cos(Radians) sa))) (+ (.y tp2) (* r (Math|Trig|Sin(Radians) sa)))
                     (Math|Float|Lerp (Math|Float|Max(Float) A0 (+ (.z tp2) 600.0)) (+ (.z tp2) 480.0) e)) :Spd (Math|Float|Lerp 700.0 160.0 e) :DT DT))
    (if (and (>= u 1.0) (< (Math|Vector|Distance(Vector) here (+ tp2 (Math|Vector|MakeVector 0.0 0.0 480.0))) 250.0))
      (Variables|Default|SetMode 3)
      (Variables|Default|SetT 0.0))
    (return))
  (if (== Mode 3)
    (if tv
      (bind a3 (Fly :P (+ (Transformation|GetActorLocation :self Target) (Math|Vector|MakeVector 0.0 0.0 480.0)) :Spd 120.0 :DT DT))
      (else (bind a3b (Fly :P here :Spd 120.0 :DT DT))))
    (if (> T 2.5)
      (if tv
        (Class|BPHuman|SetBoarded :self Target :Boarded true)
        (Rendering|SetActorHiddenInGame :self Target :bNewHidden true))
      (Variables|Default|SetMode 4)
      (Variables|Default|SetT 0.0))
    (return))
  (if (== Mode 4)
    (bind fw (Math|Vector|MakeVector (Math|Trig|Cos(Degrees) Yaw) (Math|Trig|Sin(Degrees) Yaw) 0.0))
    (bind a4 (Fly :P (+ here (+ (* fw (* 900.0 (Math|Float|Clamp(Float) (/ T 3.0) 0.0 1.0))) (Math|Vector|MakeVector 0.0 0.0 (+ 300.0 (* T 120.0))))) :Spd 900.0 :DT DT))
    (if (> (.z here) 8000.0)
      (Variables|Default|SetDone true)
      (Rendering|SetActorHiddenInGame :self self :bNewHidden true))))
''')

