# steer toward P at up to Spd (cm/s): velocity eases in/out, yaw follows the path with lag, bank = atan(v * turn rate / g),
# pitch = -atan(forward accel / g) - a little for cruise speed; keeps 32 m from the other helicopter; bobs when slow
fn('Fly', [('P', 'Vector'), ('Spd', 'float'), ('DT', 'float')], [('Arrived', 'bool')])
dsl('Fly', '''
(fn Fly (P Spd DT)
  (bind here (Transformation|GetActorLocation))
  (bind d (- P here))
  (bind len (Math|Vector|VectorLength d))
  (bind want (* (Math|Vector|Normalize d) (Math|Float|Min(Float) Spd (* len 0.45))))
  (Variables|Default|SetSep (Math|Vector|MakeVector 0.0 0.0 0.0))
  (if (Valid :A Other)
    (bind od (- here (Transformation|GetActorLocation :self Other)))
    (bind ol (Math|Vector|VectorLength od))
    (if (< ol 3200.0)
      (Variables|Default|SetSep (* (Math|Vector|Normalize od) (* (- 3200.0 ol) 0.7)))))
  (bind nv (Math|Interpolation|VInterpTo Vel (+ want Sep) DT 0.7))
  (bind hs0 (Math|Vector|VectorLength (Math|Vector|MakeVector (.x Vel) (.y Vel) 0.0)))
  (bind hs (Math|Vector|VectorLength (Math|Vector|MakeVector (.x nv) (.y nv) 0.0)))
  (bind acc (/ (- hs hs0) (Math|Float|Max(Float) DT 0.001)))
  (Variables|Default|SetVel nv)
  (bind hdg (select (> hs 150.0) (Math|Trig|Atan2(Degrees) (.y nv) (.x nv)) Yaw))
  (bind dy (* (Math|Float|Clamp(Float) (* (Math|Rotator|NormalizeAxis (- hdg Yaw)) 0.9) -30.0 30.0) DT))
  (Variables|Default|SetYaw (+ Yaw dy))
  (bind rate (Math|Trig|DegreesToRadians (/ dy (Math|Float|Max(Float) DT 0.001))))
  (bind bank (Math|Float|Clamp(Float) (* (Math|Trig|Atan2(Degrees) (* hs rate) 980.0) 1.4) -24.0 24.0))
  (bind pit (Math|Float|Clamp(Float) (- (* (Math|Trig|Atan2(Degrees) acc 980.0) -1.6) (* hs 0.006)) -16.0 12.0))
  (Variables|Default|SetRoll (Math|Interpolation|FInterpTo Roll bank DT 2.0))
  (Variables|Default|SetPitch (Math|Interpolation|FInterpTo Pitch pit DT 2.0))
  (bind bob (* (Math|Float|Clamp(Float) (- 1.0 (/ hs 300.0)) 0.0 1.0) (* 22.0 (Math|Trig|Sin(Radians) (* T 1.3)))))
  (Transformation|SetActorLocationAndRotation :self self :NewLocation (+ (+ here (* nv DT)) (Math|Vector|MakeVector 0.0 0.0 (* bob DT)))
     :NewRotation (Math|Rotator|MakeRotator Roll Pitch Yaw))
  (return (< len 120.0)))
''')

# searchlight: a ground point, eased; red onto the person the spider is chasing, a circled thing, straight down on a rescue, else a slow sweep
fn('Light', [('DT', 'float')])
dsl('Light', '''
(fn Light (DT)
  (bind here (Transformation|GetActorLocation))
  (bind fwd (Math|Vector|MakeVector (Math|Trig|Cos(Degrees) Yaw) (Math|Trig|Sin(Degrees) Yaw) 0.0))
  (bind right (Math|Vector|MakeVector (- 0.0 (Math|Trig|Sin(Degrees) Yaw)) (Math|Trig|Cos(Degrees) Yaw) 0.0))
  (bind sweep (+ (+ here (* fwd 1600.0)) (* right (* 1700.0 (Math|Trig|Sin(Radians) (* T 0.45))))))
  (Variables|Default|SetA0 0.0)
  (if (and (== Color 0) (Valid :A Spider))
    (bind vic (Class|BPTarantula|GetVictim :self Spider))
    (if (and (Valid :A vic) (> (Class|BPTarantula|GetChaseT :self Spider) 0.0))
      (Variables|Default|SetA0 1.0)
      (Variables|Default|SetAim (Math|Interpolation|VInterpTo Aim (Transformation|GetActorLocation :self vic) DT 3.0))))
  (if (and (== A0 0.0) (and (== Mode 5) (Valid :A Poi)))
    (Variables|Default|SetA0 1.0)
    (Variables|Default|SetAim (Math|Interpolation|VInterpTo Aim (Transformation|GetActorLocation :self Poi) DT 2.0)))
  (if (and (== A0 0.0) (and (>= Mode 2) (<= Mode 3)))
    (Variables|Default|SetA0 1.0)
    (Variables|Default|SetAim (Math|Interpolation|VInterpTo Aim (- here (Math|Vector|MakeVector 0.0 0.0 3000.0)) DT 2.0)))
  (if (== A0 0.0)
    (Variables|Default|SetAim (Math|Interpolation|VInterpTo Aim (Math|Vector|MakeVector (.x sweep) (.y sweep) 100.0) DT 1.2)))
  (bind d (- Aim (- here (Math|Vector|MakeVector 0.0 0.0 180.0))))
  (Rendering|Components|Light|SetIntensity :self Search :NewIntensity (Math|Float|Lerp 4000.0 35000.0 Night))
  (Transformation|SetWorldRotation :self Search :NewRotation (Math|Rotator|MakeRotator 0.0
     (Math|Trig|Atan2(Degrees) (.z d) (Math|Vector|VectorLength (Math|Vector|MakeVector (.x d) (.y d) 0.0))) (Math|Trig|Atan2(Degrees) (.y d) (.x d)))))
''')

# every 25-45 s on patrol: maybe circle a person (or the spider once it is big) for 14 s
