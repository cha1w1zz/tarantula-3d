# metachronal tetrapod gait (spider.js update): phase-driven swings while walking, settle steps while standing
fn('Gait', [('DT', 'float')])
dsl('Gait', '''
(fn Gait (DT)
  (bind L Span)
  (bind freq (Math|Float|Min(Float) 5.5 (/ (+ Speed (* (Math|Float|Absolute(Float) (Math|Trig|DegreesToRadians YawRate)) (* L 0.45))) (* L 0.24))))
  (bind moving (> freq 0.3))
  (if moving (Variables|Default|SetPhase (+ Phase (* freq DT))))
  (bind duty (Math|Float|Lerp 0.66 0.52 (Math|Float|Clamp(Float) (/ Speed (* L 1.6)) 0.0 1.0)))
  (bind sw (- 1.0 duty))
  (bind lead (select moving (* (/ duty (Math|Float|Max(Float) freq 0.01)) 0.5) 0.0))
  (Variables|Default|SetNSwing 0)
  (for i (range 8)
    (if (Utilities|Array|Get(acopy) Swing i) (Variables|Default|SetNSwing (+ NSwing 1))))
  (for i (range 8)
    (bind restW (RestAt :I i :TA 0.0))
    (if (not (Utilities|Array|Get(acopy) Swing i))
      (bind p (Math|Float|Fraction (+ Phase (Utilities|Array|Get(acopy) Off i))))
      (bind lp (Utilities|Array|Get(acopy) LastP i))
      (bind dist (Math|Vector|Distance2D(Vector) (Utilities|Array|Get(acopy) Foot i) restW))
      (if moving
        (if (and (< p sw) (or (>= lp sw) (> lp p)))
          (StartSwing :I i :Dur (/ sw freq)))
        (else
          (if (and (> dist (* L 0.06)) (< NSwing 2))
            (StartSwing :I i :Dur (Math|Random|RandomFloatinRange 0.17 0.24)))))
      (Utilities|Array|SetArrayElem LastP i p)
      (if (and (not (Utilities|Array|Get(acopy) Swing i)) (> dist (* L 0.34)))
        (StartSwing :I i :Dur 0.1)))
    (if (Utilities|Array|Get(acopy) Swing i)
      (bind st (+ (Utilities|Array|Get(acopy) SwT i) (/ DT (Utilities|Array|Get(acopy) SwDur i))))
      (Utilities|Array|SetArrayElem SwT i st)
      (bind s (Math|Float|Min(Float) st 1.0))
      (bind tgt (RestAt :I i :TA lead))
      (bind from (Utilities|Array|Get(acopy) From i))
      (bind u (Math|Float|Clamp(Float) (/ (- s 0.1) 0.8) 0.0 1.0))
      (bind e (* (* u u) (- 3.0 (* 2.0 u))))
      (bind h (Math|Float|Power (Math|Trig|Sin(Radians) (* 3.14159 (Math|Float|Min(Float) 1.0 (* s 1.08)))) 0.75))
      (bind lift (+ (* L 0.04) (* (Math|Float|Max(Float) 0.0 (- (.z tgt) (.z from))) 0.6)))
      (Utilities|Array|SetArrayElem Foot i (+ (Math|Vector|Lerp(Vector) from tgt e) (Math|Vector|MakeVector 0.0 0.0 (* h lift))))
      (Utilities|Array|SetArrayElem Tuck i h)
      (if (>= s 1.0)
        (bind fv (CamVol :P tgt :Far (+ 6000.0 (* L 2.0))))
        (if (> fv 0.03)
          (Audio|PlaySoundatLocation :Sound "/Game/Game/Sound/S_Step.S_Step" :Location tgt :VolumeMultiplier (* fv (Math|Float|Clamp(Float) (/ L 2500.0) 0.15 0.8))
             :PitchMultiplier (Math|Float|Clamp(Float) (- 1.7 (/ L 2000.0)) 0.45 1.6)))
        (Utilities|Array|SetArrayElem Swing i false)
        (Utilities|Array|SetArrayElem Tuck i 0.0)
        (Utilities|Array|SetArrayElem Foot i tgt)))
    (SolveLeg :I i)))
''')

# wander in stop-and-go bursts around Home (game.js 'wander' + drive()); body height = mean foot height + 0.09 span
fn('Move', [('DT', 'float')])
dsl('Move', '''
(fn Move (DT)
  (bind L Span)
  (bind here (Transformation|GetActorLocation))
  (Variables|Default|SetPauseT (- PauseT DT))
  (Variables|Default|SetBurstT (- BurstT DT))
  (if (and (not Hunting) (or (not HasTarget) (< (Math|Vector|Distance2D(Vector) here Target) (* L 0.4))))
    (bind ang (Math|Random|RandomFloatinRange 0.0 6.2832))
    (bind r (* (Math|Float|Max(Float) WanderRadius (* L 2.5)) (Math|Float|Sqrt (Math|Random|RandomFloat))))
    (bind c (select (>= L 1200.0) (Math|Vector|MakeVector 0.0 0.0 (.z Home)) Home))
    (bind t (+ c (Math|Vector|MakeVector (* r (Math|Trig|Cos(Radians) ang)) (* r (Math|Trig|Sin(Radians) ang)) 0.0)))
    (Variables|Default|SetTarget (Math|Vector|MakeVector (Math|Float|Clamp(Float) (.x t) -5600.0 5600.0) (Math|Float|Clamp(Float) (.y t) -3600.0 3600.0) (.z t)))
    (Variables|Default|SetHasTarget true)
    (Variables|Default|SetPauseT (select Blocked 0.0 (Math|Random|RandomFloatinRange 1.0 4.0)))
    (Variables|Default|SetBlocked false))
  (if (and (<= BurstT 0.0) (not Hunting))
    (Variables|Default|SetBurstT (Math|Random|RandomFloatinRange 1.5 4.0))
    (if (< (Math|Random|RandomFloat) 0.55)
      (Variables|Default|SetPauseT (Math|Random|RandomFloatinRange 0.5 1.8))))
  (if Hunting (Variables|Default|SetPauseT 0.0))
  (bind still (or (or (> PauseT 0.0) (== Stage 2)) Eating))
  (bind dx (- (.x Target) (.x here)))
  (bind dy (- (.y Target) (.y here)))
  (bind dYaw (Math|Rotator|NormalizeAxis (- (Math|Trig|Atan2(Degrees) dy dx) Yaw)))
  (bind wantRate (select still 0.0 (Math|Float|Clamp(Float) (* dYaw 3.5) -160.0 160.0)))
  (Variables|Default|SetYawRate (Math|Float|Lerp YawRate wantRate (Math|Float|Clamp(Float) (* DT 5.0) 0.0 1.0)))
  (Variables|Default|SetYaw (+ Yaw (* YawRate DT)))
  (bind face (Math|Float|Clamp(Float) (/ (- (Math|Trig|Cos(Degrees) dYaw) 0.2) 0.8) 0.0 1.0))
  (bind Lg (/ L 100.0))
  (bind top (* (* (* L 0.6) (Math|Float|Power (/ 9.0 (Math|Float|Max(Float) Lg 9.0)) 0.35)) 0.45))
  (bind dist (Math|Float|Sqrt (+ (* dx dx) (* dy dy))))
  (bind rush (select (and Hunting (< dist (* L 2.2))) 2.2 (select (and Hunting (> ChaseT 0.0)) 1.6 1.0)))
  (bind want (select still 0.0 (* (* (* top face) rush) (Math|Float|Clamp(Float) (/ dist (* L 0.8)) 0.2 1.0))))
  (Variables|Default|SetSpeed (Math|Interpolation|FInterpTo Speed want DT 4.0))
  (bind fwd (Math|Vector|MakeVector (Math|Trig|Cos(Degrees) Yaw) (Math|Trig|Sin(Degrees) Yaw) 0.0))
  (Variables|Default|SetVel (* fwd Speed))
  (bind zs (+ (+ (+ (.z (Utilities|Array|Get(acopy) Foot 0)) (.z (Utilities|Array|Get(acopy) Foot 1))) (+ (.z (Utilities|Array|Get(acopy) Foot 2)) (.z (Utilities|Array|Get(acopy) Foot 3))))
              (+ (+ (.z (Utilities|Array|Get(acopy) Foot 4)) (.z (Utilities|Array|Get(acopy) Foot 5))) (+ (.z (Utilities|Array|Get(acopy) Foot 6)) (.z (Utilities|Array|Get(acopy) Foot 7))))))
  (bind gz (GroundZ :P here))
  (bind zc (+ (* 0.5 (/ zs 8.0)) (* 0.5 gz)))
  (bind nz (Math|Interpolation|FInterpTo (.z here) (+ zc (* L 0.09)) DT 6.0))
  (bind np0 (+ here (* Vel DT)))
  (bind gzn (GroundZ :P (+ np0 (* fwd (* L 0.3)))))
  (bind wall (> (- gzn gz) (* L 0.35)))
  (if (and wall (not Hunting)) (Variables|Default|SetHasTarget false) (Variables|Default|SetBlocked true))
  (if (and wall Hunting) (Variables|Default|SetYaw (+ Yaw (* 150.0 DT))))
  (bind np (select wall here np0))
  (Transformation|SetActorLocationAndRotation :self self
     :NewLocation (Math|Vector|MakeVector (.x np) (.y np) nz)
     :NewRotation (Math|Rotator|MakeRotator 0.0 0.0 Yaw)))
''')


