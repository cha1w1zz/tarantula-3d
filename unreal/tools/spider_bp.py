# hip -> knee -> ankle analytic 2-bone IK; metatarsus hangs from the ankle, tarsus lies on the ground (spider.js solve())
fn('SolveLeg', [('I', 'int')])
dsl('SolveLeg', '''
(fn SolveLeg (I)
  (bind L Span)
  (bind a (Utilities|Array|Get(acopy) LA I))
  (bind b (Utilities|Array|Get(acopy) LB I))
  (bind c (Utilities|Array|Get(acopy) LC I))
  (bind t (Utilities|Array|Get(acopy) LT I))
  (bind tk (Utilities|Array|Get(acopy) Tuck I))
  (bind foot (Utilities|Array|Get(acopy) Foot I))
  (bind hip (Math|Transform|TransformLocation (Transformation|GetActorTransform) (Utilities|Array|Get(acopy) HipL I)))
  (bind up (Math|Vector|MakeVector 0.0 0.0 1.0))
  (bind out (Math|Vector|Normalize (Math|Vector|MakeVector (- (.x foot) (.x hip)) (- (.y foot) (.y hip)) 0.0)))
  (bind tdir (Math|Vector|Normalize (+ out (* up (- -0.22 (* 0.55 tk))))))
  (bind base (- foot (* tdir t)))
  (bind ad (Math|Vector|Normalize (- (* up (+ 0.55 (* 0.3 tk))) (* out (- 0.83 (* 0.3 tk))))))
  (bind ank0 (+ base (* ad c)))
  (bind dir (Math|Vector|Normalize (- ank0 hip)))
  (bind d (Math|Float|Clamp(Float) (Math|Vector|VectorLength (- ank0 hip)) (+ (Math|Float|Absolute(Float) (- a b)) 0.1) (* (+ a b) 0.998)))
  (bind ankle (+ hip (* dir d)))
  (bind x (/ (+ (- (* a a) (* b b)) (* d d)) (* 2.0 d)))
  (bind y (Math|Float|Sqrt (Math|Float|Max(Float) 0.0 (- (* a a) (* x x)))))
  (bind bend (Math|Vector|Normalize (+ up (* out 0.35))))
  (bind perp (Math|Vector|Normalize (- bend (* dir (Math|Vector|DotProduct bend dir)))))
  (bind knee (+ (+ hip (* dir x)) (* perp y)))
  (bind k (* I 4))
  (Seg :Idx k :A hip :B knee :R (* L 0.017))
  (Seg :Idx (+ k 1) :A knee :B ankle :R (* L 0.015))
  (Seg :Idx (+ k 2) :A ankle :B base :R (* L 0.011))
  (Seg :Idx (+ k 3) :A base :B foot :R (* L 0.009))
  (bind j (* I 3))
  (Knob :Idx j :P knee :R (* L 0.0165))
  (Knob :Idx (+ j 1) :P ankle :R (* L 0.0128))
  (Knob :Idx (+ j 2) :P base :R (* L 0.0092)))
''')

