# keyboard, mouse and the HUD buttons (buttons polled: fire when released)
fn('Controls', [('DT', 'float')])
dsl('Controls', '''
(fn Controls (DT)
  (bind pc (Game|GetPlayerController :PlayerIndex 0))
  (bind (mx my) (Game|Player|GetInputMouseDelta :self pc))
  (if (Game|Player|IsInputKeyDown :self pc :Key "RightMouseButton")
    (Variables|Default|SetYaw (+ Yaw (* mx 0.3)))
    (Variables|Default|SetPitch (Math|Float|Clamp(Float) (+ Pitch (* my 0.3)) -85.0 -4.0)))
  (if (Game|Player|WasInputKeyJustPressed :self pc :Key "MouseScrollUp") (Variables|Default|SetDist (Math|Float|Max(Float) 350.0 (* Dist 0.86))))
  (if (Game|Player|WasInputKeyJustPressed :self pc :Key "MouseScrollDown") (Variables|Default|SetDist (Math|Float|Min(Float) 11000.0 (* Dist 1.16))))
  (bind fwd (Math|Vector|MakeVector (Math|Trig|Cos(Degrees) Yaw) (Math|Trig|Sin(Degrees) Yaw) 0.0))
  (bind right (Math|Vector|MakeVector (- 0.0 (Math|Trig|Sin(Degrees) Yaw)) (Math|Trig|Cos(Degrees) Yaw) 0.0))
  (bind f (- (select (Game|Player|IsInputKeyDown :self pc :Key "W") 1.0 0.0) (select (Game|Player|IsInputKeyDown :self pc :Key "S") 1.0 0.0)))
  (bind r (- (select (Game|Player|IsInputKeyDown :self pc :Key "D") 1.0 0.0) (select (Game|Player|IsInputKeyDown :self pc :Key "A") 1.0 0.0)))
  (if (or (!= f 0.0) (!= r 0.0))
    (Variables|Default|SetFollow false)
    (bind mv (* (+ (* fwd f) (* right r)) (* (* Dist 0.7) DT)))
    (bind nf (+ Focus mv))
    (Variables|Default|SetFocus (Math|Vector|MakeVector (Math|Float|Clamp(Float) (.x nf) -6500.0 6500.0) (Math|Float|Clamp(Float) (.y nf) -4500.0 4500.0) (.z nf))))
  (bind b1 (Button|IsPressed :self (Class|WBPHUD|GetBtnCricket :self HUD)))
  (bind b2 (Button|IsPressed :self (Class|WBPHUD|GetBtnDubia :self HUD)))
  (bind b3 (Button|IsPressed :self (Class|WBPHUD|GetBtnMist :self HUD)))
  (bind b4 (Button|IsPressed :self (Class|WBPHUD|GetBtnFollow :self HUD)))
  (bind b5 (Button|IsPressed :self (Class|WBPHUD|GetBtnSpeed :self HUD)))
  (bind b6 (Button|IsPressed :self (Class|WBPHUD|GetBtnHelp :self HUD)))
  (if (or (Game|Player|WasInputKeyJustPressed :self pc :Key "One") (and P1 (not b1))) (SpawnPrey :Kind 0))
  (if (or (Game|Player|WasInputKeyJustPressed :self pc :Key "Two") (and P2 (not b2))) (SpawnPrey :Kind 1))
  (if (or (Game|Player|WasInputKeyJustPressed :self pc :Key "M") (and P3 (not b3))) (Mist))
  (if (or (Game|Player|WasInputKeyJustPressed :self pc :Key "F") (and P4 (not b4))) (ToggleFollow))
  (if (or (Game|Player|WasInputKeyJustPressed :self pc :Key "T") (and P5 (not b5))) (CycleSpeed))
  (if (or (Game|Player|WasInputKeyJustPressed :self pc :Key "H") (and P6 (not b6))) (ToggleHelp))
  (Variables|Default|SetP1 b1) (Variables|Default|SetP2 b2) (Variables|Default|SetP3 b3)
  (Variables|Default|SetP4 b4) (Variables|Default|SetP5 b5) (Variables|Default|SetP6 b6))
''')

