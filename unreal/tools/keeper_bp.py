# release prey: max 4, never while molting / soft (live prey is dangerous then), away from the spider, not in the pond
fn('SpawnPrey', [('Kind', 'int')])
dsl('SpawnPrey', '''
(fn SpawnPrey (Kind)
  (bind all (Actor|GetAllActorsOfClass :ActorClass "/Game/Game/BP_Prey.BP_Prey_C"))
  (bind st (Class|BPTarantula|GetStage :self Spider))
  (if (>= (Utilities|Array|Length all) 4)
    (Say :Msg "ในตู้มีเหยื่อครบ 4 ตัวแล้ว")
    (elif (>= st 2)
      (Say :Msg "ห้ามให้อาหารตอนลอกคราบ/ตัวนิ่ม — เหยื่อเป็นอันตรายต่อแมงมุม")
      (else
        (bind span (Class|BPTarantula|GetSpan :self Spider))
        (bind sp (Transformation|GetActorLocation :self Spider))
        (Variables|Default|SetFound false)
        (for i (range 30)
          (bind p (Math|Vector|MakeVector (Math|Random|RandomFloatinRange -5200.0 1300.0) (Math|Random|RandomFloatinRange -700.0 3500.0) 600.0))
          (bind ok (and (> (Math|Vector|Distance2D(Vector) p sp) (+ (* span 2.5) 600.0)) (> (Math|Vector|Distance2D(Vector) p (Math|Vector|MakeVector 300.0 2550.0 0.0)) 850.0)))
          (if (and ok (not Found))
            (Variables|Default|SetFound true)
            (Variables|Default|SetSpawnP p)))
        (bind a (Game|SpawnActorfromClass :Class "/Game/Game/BP_Prey.BP_Prey_C"
                   :SpawnTransform (Math|Transform|MakeTransform :Location SpawnP) :CollisionHandlingOverride "AlwaysSpawn"))
        (Class|BPPrey|SetKind :self a :Kind Kind)
        (Class|BPPrey|SetK :self a :K (/ span 1200.0))
        (Class|BPPrey|Setup :self a)
        (if (== st 1) (Say :Msg "ช่วงก่อนลอกคราบ แมงมุมจะไม่กินอาหาร"))
        (Log :Msg (select (== Kind 0) "ปล่อยจิ้งหรีดลงตู้" "ปล่อยแมลงสาบดูเบียลงตู้"))))))
''')

