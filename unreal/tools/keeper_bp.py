dsl('UpdateHUD', '''
(fn UpdateHUD (DT)
  (bind st (Class|BPTarantula|GetStage :self Spider))
  (bind meals (Class|BPTarantula|GetMeals :self Spider))
  (if (> meals LastMeals) (Log :Msg "แมงมุมจับเหยื่อกินแล้ว"))
  (if (!= st LastStage) (Log :Msg (Utilities|String|Append "ระยะ: " (StageName :S st))))
  (Variables|Default|SetLastMeals meals)
  (Variables|Default|SetLastStage st)
  (bind h (Math|Float|Truncate Hours))
  (bind m (Math|Float|Truncate (* (- Hours h) 60.0)))
  (bind clock (Utilities|String|Append (Utilities|String|Append (select (< h 10) "0" "") (Utilities|String|ToString(Integer) h))
                 (Utilities|String|Append (select (< m 10) ":0" ":") (Utilities|String|ToString(Integer) m))))
  (bind a (Utilities|String|Append (Pct :Label "ความหิว  " :V (Class|BPTarantula|GetHunger :self Spider) :Unit "%")
                                 (Pct :Label "ความชื้น  " :V Hum :Unit "%")))
  (bind b (Utilities|String|Append (Pct :Label "อุณหภูมิ  " :V Temp :Unit " °C")
                                 (Pct :Label "การเติบโต  " :V (Class|BPTarantula|GetGrowth :self Spider) :Unit "%")))
  (bind c (Utilities|String|Append (Utilities|String|Append "ระยะ  " (StageName :S st))
             (Utilities|String|Append (Utilities|String|Append NL "ขนาดขา  ") (Utilities|String|Append (Utilities|String|ToString(Float) (/ (Math|Float|Round (/ (Class|BPTarantula|GetSpan :self Spider) 10.0)) 10.0)) (Utilities|String|Append " ซม." NL)))))
  (bind d (Utilities|String|Append (Utilities|String|Append "ลอกคราบ " (Utilities|String|ToString(Integer) (Class|BPTarantula|GetMolts :self Spider)))
             (Utilities|String|Append " ครั้ง · กินไป " (Utilities|String|Append (Utilities|String|ToString(Integer) meals) (Utilities|String|Append " ตัว" NL)))))
  (bind e (Utilities|String|Append (Utilities|String|Append "วันที่ " (Utilities|String|ToString(Integer) Day))
             (Utilities|String|Append (Utilities|String|Append "  เวลา " clock) (Utilities|String|Append "  ×" (Utilities|String|ToString(Integer) (Math|Float|Round TimeMul))))))
  (Widget|SetText(Text) :self (Class|WBPHUD|GetTxtStats :self HUD) :InText (Utilities|Text|ToText(String) (Utilities|String|Append (Utilities|String|Append a b) (Utilities|String|Append (Utilities|String|Append c d) e))))
  (Widget|SetText(Text) :self (Class|WBPHUD|GetTxtLog :self HUD) :InText (Utilities|Text|ToText(String) (Utilities|String|Append (Utilities|String|Append "บันทึก" NL) LogText)))
  (Variables|Default|SetNoticeT (- NoticeT DT))
  (Widget|SetText(Text) :self (Class|WBPHUD|GetTxtNotice :self HUD) :InText (Utilities|Text|ToText(String) (select (> NoticeT 0.0) Notice ""))))
''')

