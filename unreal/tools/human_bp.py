# brain: 0 hide (still), 1 flee, 2 trip to store/pond, 3 act (eat/drink), 4 wander to another hide spot
fn('Think', [('DT', 'float'), ('Days', 'float')])
dsl('Think', '''
(fn Think (DT Days)
  (Variables|Default|SetStateT (+ StateT DT))
  (Variables|Default|SetSayT (- SayT DT))
  (Variables|Default|SetGrief (- Grief DT))
  (Variables|Default|SetFood (Math|Float|Max(Float) 0.0 (- Food (/ Days 5.0))))
  (Variables|Default|SetWater (Math|Float|Max(Float) 0.0 (- Water (/ Days 3.5))))
  (bind here (Transformation|GetActorLocation))
  (bind sp (Transformation|GetActorLocation :self Spider))
  (bind span (Class|BPTarantula|GetSpan :self Spider))
  (bind dsp (Math|Vector|Distance2D(Vector) here sp))
  (bind hunted (and (Class|BPTarantula|GetHunting :self Spider) (== (Class|BPTarantula|GetVictim :self Spider) self)))
  (bind fear (+ 900.0 (* span 0.9)))
  (bind danger (or (< dsp fear) (and hunted (< dsp (* fear 2.2)))))
  (if (and danger (!= State 1))
    (Variables|Default|SetState 1) (Variables|Default|SetStateT 0.0)
    (Variables|Default|SetTarget (Pick :L 0 :Away true :Fear (* fear 0.8)))
    (Talk :Msg (select (== Who 0) "มันมาแล้ว!! วิ่ง!!" "ไม่ไหวแล้ว โค้ดชีวิตนี้มีบั๊ก!!")))
  (if (and (== State 1) (> StateT 1.2) (not danger))
    (Variables|Default|SetState 0) (Variables|Default|SetStateT 0.0)
    (Variables|Default|SetTarget (Pick :L 0 :Away false :Fear fear)))
  (if (and (== State 1) (> StateT 1.5) danger (< (Math|Vector|Distance2D(Vector) here Target) 150.0))
    (Variables|Default|SetStateT 0.0)
    (Variables|Default|SetTarget (Pick :L 0 :Away true :Fear (* fear 0.8))))
  (if (and (== State 0) (> StateT (Math|Random|RandomFloatinRange 6.0 12.0)) (<= Grief 0.0))
    (Variables|Default|SetStateT 0.0)
    (if (or (< Food 0.55) (< Water 0.55))
      (Variables|Default|SetState 2)
      (Variables|Default|SetTripFood (<= Food Water))
      (Variables|Default|SetTarget (Pick :L (select TripFood 1 2) :Away false :Fear fear))
      (Talk :Msg (select TripFood (select (== Who 0) "หิวแล้ว ไปหาข้าวปั้นที่ร้านดีกว่า" "ท้องร้องเป็นเสียง compile error")
                                  (select (== Who 0) "คอแห้ง ไปหาน้ำที่บ่อ" "ต้องการ H2O ด่วน")))
      (else
        (Variables|Default|SetState 4)
        (Variables|Default|SetTarget (Pick :L 0 :Away false :Fear fear)))))
  (if (and (or (== State 2) (== State 4)) (< (Math|Vector|Distance2D(Vector) here Target) 140.0))
    (Variables|Default|SetStateT 0.0)
    (Variables|Default|SetState (select (== State 2) 3 0)))
  (if (and (== State 3) (> StateT 3.4))
    (if TripFood (Variables|Default|SetFood 1.0) (else (Variables|Default|SetWater 1.0)))
    (Talk :Msg (select TripFood "อิ่มแล้ว กลับไปหลบก่อน" "ชื่นใจ... กลับไปหลบ"))
    (Variables|Default|SetState 0) (Variables|Default|SetStateT 0.0)
    (Variables|Default|SetTarget (Pick :L 0 :Away false :Fear fear))))
''')

fn('Move', [('DT', 'float')])
dsl('Move', '''
(fn Move (DT)
  (bind here (Transformation|GetActorLocation))
  (bind dist (Math|Vector|Distance2D(Vector) here Target))
  (bind flee (== State 1))
  (bind urgent (or (< Food 0.2) (< Water 0.2)))
  (bind sprint (and flee (> Stamina 0.05)))
  (Variables|Default|SetStamina (Math|Float|Clamp(Float) (+ Stamina (* DT (select sprint -0.18 0.08))) 0.0 1.0))
  (bind top (select flee (select sprint 950.0 480.0) (select (== State 2) (select urgent 320.0 150.0) 140.0)))
  (bind still (or (or (== State 3) (< dist 60.0)) (and (== State 0) (< dist 100.0))))
  (bind dx (- (.x Target) (.x here)))
  (bind dy (- (.y Target) (.y here)))
  (bind dYaw (Math|Rotator|NormalizeAxis (- (Math|Trig|Atan2(Degrees) dy dx) Yaw)))
  (bind turn (select flee 720.0 300.0))
  (if (not still) (Variables|Default|SetYaw (+ Yaw (Math|Float|Clamp(Float) dYaw (* turn (- 0.0 DT)) (* turn DT)))))
  (bind face (Math|Float|Clamp(Float) (/ (- (Math|Trig|Cos(Degrees) dYaw) 0.2) 0.8) 0.0 1.0))
  (bind want (select still 0.0 (* top face)))
  (Variables|Default|SetSpeed (Math|Interpolation|FInterpTo Speed want DT (select flee 8.0 4.0)))
  (bind fwd (Math|Vector|MakeVector (Math|Trig|Cos(Degrees) Yaw) (Math|Trig|Sin(Degrees) Yaw) 0.0))
  (bind np (+ here (* fwd (* Speed DT))))
  (bind g0 (GroundZ :P here))
  (bind g1 (GroundZ :P (+ here (* fwd 45.0))))
  (bind wall (> (- g1 g0) 60.0))
  (if wall (Variables|Default|SetYaw (+ Yaw (* (select (> dYaw 0.0) 1.0 -1.0) (* 400.0 DT)))))
  (bind np2 (select wall here np))
  (bind gz (GroundZ :P np2))
  (Variables|Default|SetStuckT (+ StuckT DT))
  (if (> StuckT 1.6)
    (if (and (not still) (< (Math|Vector|Distance2D(Vector) here LastP) 60.0))
      (Variables|Default|SetTarget (Pick :L 0 :Away flee :Fear 0.0)))
    (Variables|Default|SetStuckT 0.0)
    (Variables|Default|SetLastP here))
  (Transformation|SetActorLocationAndRotation :self self
     :NewLocation (Math|Vector|MakeVector (.x np2) (.y np2) (Math|Interpolation|FInterpTo (.z here) gz DT 14.0))
     :NewRotation (Math|Rotator|MakeRotator 0.0 0.0 Yaw)))
''')

