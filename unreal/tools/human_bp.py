# walk cycle: legs / arms swing with Phase, bob; held = kick and wave
fn('Pose', [('DT', 'float')])
dsl('Pose', '''
(fn Pose (DT)
  (bind rate (select Held 3.0 (/ Speed (* 120.0 Hs))))
  (Variables|Default|SetPhase (+ Phase (* rate DT)))
  (bind amp (select Held 1.4 (Math|Float|Clamp(Float) (/ Speed 300.0) 0.0 1.0)))
  (bind s (Math|Trig|Sin(Radians) (* Phase 6.2832)))
  (bind lg (* (* s 38.0) amp))
  (bind ar (* (* s -30.0) amp))
  (bind up (select Held 150.0 0.0))
  (Transformation|SetRelativeRotation :self HipL :NewRotation (Math|Rotator|MakeRotator 0.0 lg 0.0))
  (Transformation|SetRelativeRotation :self HipR :NewRotation (Math|Rotator|MakeRotator 0.0 (- 0.0 lg) 0.0))
  (Transformation|SetRelativeRotation :self ShL :NewRotation (Math|Rotator|MakeRotator 0.0 (+ ar up) 0.0))
  (Transformation|SetRelativeRotation :self ShR :NewRotation (Math|Rotator|MakeRotator 0.0 (- up ar) 0.0)))
''')

# best spot of a list: far from the spider (Away) or near me (not Away), never within Fear of the spider
fn('Pick', [('L', 'int'), ('Away', 'bool'), ('Fear', 'float')], [('P', 'Vector')])
dsl('Pick', '''
(fn Pick (L Away Fear)
  (if (== L 0) (Variables|Default|SetCur Hides))
  (if (== L 1) (Variables|Default|SetCur Stores))
  (if (== L 2) (Variables|Default|SetCur Pond))
  (bind here (Transformation|GetActorLocation))
  (bind sp (Transformation|GetActorLocation :self Spider))
  (Variables|Default|SetBest -1000000000.0)
  (Variables|Default|SetBestP here)
  (for p Cur
    (bind dm (Math|Vector|Distance2D(Vector) p here))
    (bind ds (Math|Vector|Distance2D(Vector) p sp))
    (bind side (Math|Vector|DotProduct (Math|Vector|Normalize (- p here)) (Math|Vector|Normalize (- sp here))))
    (bind score (select Away (- (- ds (* dm 0.6)) (* side 1500.0)) (- (+ (* (Math|Random|RandomFloat) 1500.0) (* ds 0.2)) dm)))
    (if (and (> ds Fear) (> score Best))
      (Variables|Default|SetBest score)
      (Variables|Default|SetBestP p)))
  (return BestP))
''')

